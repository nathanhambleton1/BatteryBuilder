function P = blockParameterList()
%BLOCKPARAMETERLIST  Every Battery (Table-Based) value the Modeling tab shows.
%
%   One row per box. Only the parameters that are ACTIVE in the block set-up
%   this project uses are listed:
%     Charge dynamics          : 1..3 time-constant dynamics (RC pairs)
%     Tabulate over temperature: No   (one test file = one temperature)
%     Current directionality   : No
%     Self-discharge           : Disabled unless you fill in Rleak
%     Thermal port             : Model
%     Expose SOC port          : Yes
%     Fade / calendar aging    : Disabled
%
%   Fields
%     key    internal name (matches extractCellParameters)
%     label  text shown next to the box
%     var    base-workspace variable the Save button writes
%     where  where the variable goes in the block dialog
%     unit   unit the value is in (set the same unit in the block)
%     group  heading the row sits under
%     need   'required' | 'optional' | 'setting'
%     hint   what to look for on a datasheet if the data cannot give it
%     rc     RC pair number for R/tau rows (0 otherwise)
%     isVec  true if the block wants one value per SOC breakpoint

B = 'Battery (Table-Based) block';
P = struct('key',{},'label',{},'var',{},'where',{},'unit',{},'group',{}, ...
           'need',{},'hint',{},'rc',{},'isVec',{});

add('SOC_vec', 'SOC breakpoints', 'batt_SOC_vec', ...
    [B ' > Main > Vector of state-of-charge values, SOC'], '-', 'Main', 'setting', ...
    'The SOC points every table is given at. Edit before pressing Extract if you want other points.', 0, false);
add('V0_vec', 'Open-circuit voltage V0(SOC)', 'batt_V0_vec', ...
    [B ' > Main > Open-circuit voltage, V0(SOC)'], 'V', 'Main', 'required', ...
    'Datasheet OCV-vs-SOC curve (read one value per SOC breakpoint).', 0, true);
add('V_range', 'Terminal voltage range [Min Max]', 'batt_V_range', ...
    [B ' > Main > Terminal voltage operating range [Min Max]'], 'V', 'Main', 'optional', ...
    'Datasheet discharge cut-off and maximum charge voltage, e.g. [2.5 4.2].', 0, false);
add('R0_vec', 'Terminal resistance R0(SOC)', 'batt_R0_vec', ...
    [B ' > Main > Terminal resistance, R0(SOC)'], 'Ohm', 'Main', 'required', ...
    'Datasheet DC internal resistance (one number is copied to every SOC point).', 0, true);
add('AH', 'Cell capacity AH', 'batt_AH', ...
    [B ' > Main > Cell capacity, AH'], 'A*hr', 'Main', 'required', ...
    'Datasheet nominal / rated capacity.', 0, false);
add('Rleak', 'Self-discharge resistance Rleak', 'batt_Rleak', ...
    [B ' > Main > Self-discharge = Enabled > Self-discharge resistance, Rleak'], 'Ohm', 'Main', 'optional', ...
    ['Not measurable in a normal cycling test. Leave empty to keep self-discharge disabled. ' ...
     'From a datasheet monthly self-discharge: Rleak = V_nominal / I_leak, ' ...
     'I_leak (A) = capacity (Ah) x monthly fraction / 720 h.'], 0, false);

names = {'First','Second','Third'};
for q = 1:3
    add(sprintf('R%d_vec',q), sprintf('Polarization resistance R%d(SOC)',q), sprintf('batt_R%d_vec',q), ...
        sprintf('%s > Dynamics > %s polarization resistance, R%d(SOC)', B, names{q}, q), 'Ohm', ...
        'Dynamics (RC pairs)', 'required', ...
        'Almost never on a datasheet. Needs rests (>= 5 min) after charges, discharges or pulses in the test.', q, true);
    add(sprintf('tau%d_vec',q), sprintf('Time constant tau%d(SOC)',q), sprintf('batt_tau%d_vec',q), ...
        sprintf('%s > Dynamics > %s time constant, tau%d(SOC)', B, names{q}, q), 's', ...
        'Dynamics (RC pairs)', 'required', ...
        'Almost never on a datasheet. Needs rests (>= 5 min) after charges, discharges or pulses in the test.', q, true);
end

add('thermal_mass', 'Thermal mass', 'batt_thermal_mass', ...
    [B ' > Thermal > Thermal mass'], 'J/K', 'Thermal', 'required', ...
    'Cell mass (kg) x specific heat (J/kg/K). Mass is on the datasheet; specific heat of Li-ion cells is usually quoted by the maker.', 0, false);
add('hA', 'Convection h*A (outside the block)', 'batt_hA', ...
    ['NOT a battery parameter: Convective Heat Transfer block between battery port H and the ambient. ' ...
     'Set Area = 1 m^2 and Heat transfer coefficient = batt_hA W/(m^2*K)'], 'W/K', 'Thermal', 'optional', ...
    'Depends on your fixture / cooling, not on the cell - only a temperature-logged test can give it.', 0, false);

add('SOC0', 'Initial state of charge', 'batt_SOC0', ...
    [B ' > Initial Targets > State of charge'], '-', 'Initial targets', 'optional', ...
    'SOC (0..1) the simulation starts at.', 0, false);
add('T0', 'Initial cell temperature', 'batt_T0', ...
    [B ' > Initial Targets > Cell temperature'], 'K', 'Initial targets', 'optional', ...
    'Cell temperature the simulation starts at (K = °C + 273.15).', 0, false);

    function add(key, label, var, where, unit, group, need, hint, rc, isVec)
        P(end+1) = struct('key',key,'label',label,'var',var,'where',where,'unit',unit, ...
            'group',group,'need',need,'hint',hint,'rc',rc,'isVec',isVec);
    end
end
