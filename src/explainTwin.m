function fig = explainTwin(res)
%EXPLAINTWIN  The digital twin's "How?" window (Modeling tab, button 3).
%
%   explainTwin(res)    res = runDigitalTwin(...) result
%
%   Left: what the twin is, why it is built that way, the equations, each step
%   with the EXACT code that does it (read live from the source files, with
%   file:line), which graph checks which property, and the key-point table.
%   Right: the comparison graphs.

fig = [];
if isempty(res), return; end
here = fileparts(fileparts(mfilename('fullpath')));
tw = res.tw; T = res.table;

fig = uifigure('Name', ['Digital twin - ' res.name], 'Color', 'w');
fig.Position(3:4) = [1500 900]; movegui(fig, 'center');
g = uigridlayout(fig, [1 2], 'ColumnWidth', {'1x', '1.15x'}, 'Padding', [6 6 6 6]);
h = uihtml(g); h.HTMLSource = page();
tg = uitabgroup(g);
titles = {'Whole test','Discharges','First 2 min (R0 + RC)','Charges'};
tags = {'_twin_overview','_twin_discharges','_twin_steps','_twin_charges'};
for k = 1:numel(tags)
    f = res.files(contains(res.files, tags{k}));
    if isempty(f), continue; end
    t = uitab(tg, 'Title', titles{k});
    gi = uigridlayout(t, [1 1], 'Padding', [2 2 2 2]);
    uiimage(gi, 'ImageSource', f{1}, 'ScaleMethod', 'fit');
end

    function s = page()
        dis = contains(T.Phase, "Discharge"); chg = contains(T.Phase, "Charge"); rst = T.Phase == "Rest";
        worst = @(m) max(abs(m));
        keyErr = [T.err_start_mV T.err_end_mV T.err_min_mV T.err_max_mV];
        Ivec = strjoin(compose('%.3g', tw.I_vec), ', ');
        s = ['<html><head><style>' ...
            'html,body{overflow-x:hidden} body{font-family:Segoe UI,Arial;font-size:13px;color:#1b1b1b;margin:10px 24px 10px 14px;line-height:1.45;box-sizing:border-box;max-width:calc(100vw - 60px)}' ...
            'h2{font-size:16px;margin:18px 0 6px;color:#2a4f8a} h1{font-size:19px;margin:4px 0 8px}' ...
            'pre{background:#f4f4f2;border-left:3px solid #2a78d6;padding:6px 8px;font-size:11px;white-space:pre-wrap}' ...
            '.f{color:#6b6a66;font-size:11px;margin:6px 0 -4px} .eq{font-family:Consolas,monospace;background:#fafaf8;padding:6px 8px}' ...
            'table{border-collapse:collapse;font-size:11.5px} td,th{border:1px solid #ddd;padding:2px 6px;text-align:right}' ...
            'th{background:#f0f0ee} td:nth-child(2){text-align:left} .big{font-size:15px}' ...
            '</style></head><body>' ...
            sprintf('<h1>Digital twin of %s</h1>', esc(res.name)) ...
            sprintf(['<p class="big">Voltage: <b>%.1f mV rms</b> over the whole %.0f h test ' ...
            '(the Modeling-tab values in Battery (Table-Based): %.0f mV). Temperature: <b>%.1f K rms</b>.<br>' ...
            'Start of the test: <b>%+.1f mV</b>. End of the test: <b>%+.1f mV</b>. ' ...
            'Every discharge ends (cut-off) within <b>%.1f mV</b>; highest point of every charge within <b>%.1f mV</b>.</p>'], ...
            res.rms_mV, res.t(end)/3600, res.rmsTB_mV, res.rmsT_K, T.err_start_mV(1), T.err_end_mV(end), ...
            worst(T.err_end_mV(dis)), worst(T.err_max_mV(chg))) ...
            '<h2>1. In one sentence</h2>' ...
            '<p>Drive a battery model with the <b>measured current</b>, and choose every number in its tables so that ' ...
            'its voltage is as close as possible to the <b>measured voltage over the whole test</b> &ndash; then run that ' ...
            'model in Simulink and check it lands on the curves.</p>' ...
            '<h2>2. Why not just the boxes on this tab?</h2>' ...
            '<p>The boxes go into <b>Battery (Table-Based)</b>, which has <i>one</i> resistance per SOC. This cell''s resistance ' ...
            'falls when the current rises: 12 s into the 0.1C discharge it shows about twice the resistance it shows at the ' ...
            'max-rate discharge. One number cannot do both, so that model misses the fast discharge by up to ~1 V ' ...
            '(orange curves in the graphs). The Simscape Battery block <b>Battery Equivalent Circuit</b> has the same tables ' ...
            'plus a <b>current axis</b>: every discharge rate of the test gets its own column. That is the only change of model.</p>' ...
            sprintf(['<p>Current breakpoints found in this file (A, + = charge): <b>%s</b>. A file with a different last ' ...
            'C-rate simply gets a different last column.</p>'], Ivec) ...
            '<h2>3. The model (I + = charge)</h2><div class="eq">' ...
            'V = V0(SOC) + I&middot;R0(SOC,I) + U1 + U2 + U3 &nbsp;&nbsp;&nbsp; terminal voltage<br>' ...
            'dUk/dt = (I&middot;Rk(SOC,I) &minus; Uk) / &tau;k &nbsp;&nbsp;&nbsp; 3 RC pairs<br>' ...
            'SOC = SOC0 + &int;I dt / (3600&middot;AH) &nbsp;&nbsp;&nbsp; coulomb counting<br>' ...
            'm&middot;cp&middot;dT/dt = I&middot;(V &minus; V0) &minus; hA&middot;(T &minus; T<sub>chamber</sub>) &nbsp;&nbsp; heat = the voltage the cell loses &times; I</div>' ...
            sprintf(['<p>Fitted here: &tau;1 = %.2g s, &tau;2 = %.3g s, &tau;3 = %.3g h &nbsp;|&nbsp; m&middot;cp = %.1f J/K, ' ...
            'h&middot;A = %.4f W/K &nbsp;|&nbsp; AH = %.4g Ah, SOC0 = %.4f (from step 1 of this tab).</p>'], ...
            tw.tau1, tw.tau2, tw.tau3/3600, tw.thermal_mass, tw.hA, tw.AH, tw.SOC0) ...
            '<p>&tau;1 (under a second) is the instant part of every step, &tau;2 (minutes) the bend after it, ' ...
            '&tau;3 (hours) the slow creep of the voltage after a discharge to cut-off.</p>' ...
            '<h2>4. How the numbers are found &ndash; the code</h2>' ...
            '<p><b>a) SOC</b> is coulomb counting from SOC0, exactly as the block does it:</p>' ...
            snip('src/fitDigitalTwin.m', 'soc = SOC0 + [0; cumsum', 1) ...
            '<p><b>b) Everything is a sum.</b> For fixed time constants the voltage is (table value) &times; (a known signal): ' ...
            'V0 times the SOC interpolation weights, R0 times weights&times;I, Rk times weights&times;I smoothed with &tau;k. ' ...
            'So <i>all</i> table values come from <b>one least-squares solve</b> &ndash; no guessing, no iterating on hundreds of numbers:</p>' ...
            snip('src/fitDigitalTwin.m', 'Wv = full(lookupWeights', 3) ...
            snip('src/fitDigitalTwin.m', 'function [e, x] = solveTables', 30) ...
            '<p>The rules in that solve: every R &ge; a small floor (the block needs R &gt; 0), V0 rises with SOC, and the tables ' ...
            'are kept smooth so SOC / current corners the test never visits get sensible values. The start of the test, and the ' ...
            'first / last / lowest / highest point of every charge, discharge and rest count 10&times; (the opening rest 100&times;), ' ...
            'so the twin starts, turns and ends where the cell does:</p>' ...
            snip('src/fitDigitalTwin.m', 'w = ones(N,1);', 14) ...
            '<p><b>c) Three time constants</b> are the only numbers searched (fminsearch around the solve above):</p>' ...
            snip('src/fitDigitalTwin.m', 'z = fminsearch(@(z) solveTables', 2) ...
            '<p><b>d) Thermal mass and h&middot;A</b>: the twin''s own heat I&middot;(V &minus; V0) through one thermal mass with the ' ...
            'chamber as the ambient, fitted to the measured cell temperature:</p>' ...
            snip('src/fitDigitalTwin.m', 'cost = @(p) rms(thermal', 3) ...
            '<p><b>e) The same equations in MATLAB</b> (used by the fit, and to cross-check Simulink: they agree within ' ...
            sprintf('%.1f mV rms):</p>', res.rmsMatlabCopy_mV) ...
            snip('src/simulateTwinFast.m', 'V = v0 + I.*r0 + sum(U, 2);', 2) ...
            '<h2>5. The Simulink model (BatteryTwin.slx)</h2>' ...
            '<p>Measured current &rarr; Controlled Current Source &rarr; the battery. Top: the twin; bottom: this tab''s boxes in ' ...
            'Battery (Table-Based), on the same current and chamber. The twin block''s settings:</p>' ...
            snip('src/buildTwinModel.m', 'set_param(ec, ...', 13) ...
            '<p>and its heat, which goes into a Thermal Mass and a Convective Heat Transfer block to the chamber:</p>' ...
            snip('src/buildTwinModel.m', "'Q = I*(V - V0)'", 1) ...
            '<p>Run it yourself: <b>runDigitalTwin(''cell.csv'')</b>, or a list / folder of files with the same cycle.</p>' ...
            '<h2>6. Which graph checks what</h2><ul>' ...
            '<li><b>Whole test</b>: the voltage on top of the measurement, the error trace (mV), and the cell temperature.</li>' ...
            '<li><b>Discharges</b>: every discharge on its own &ndash; the start, the curve, the knee and the cut-off minimum, ' ...
            'and the first hour of recovery after it.</li>' ...
            '<li><b>First 2 min</b> (log time): the instant drop is R0, the curve after it is the RC pairs &ndash; the ' ...
            '&quot;reaction&quot; of the cell to a step. Includes the dip and recovery of the max-rate discharge.</li>' ...
            '<li><b>Charges</b>: the climb to the CV voltage, the top of charge, and how it settles in the rest.</li></ul>' ...
            '<h2>7. Key points, every phase (twin &minus; measured, mV)</h2>' tableHtml() ...
            '<h2>8. What is left</h2><ul>' ...
            sprintf('<li>Largest key-point error: <b>%.1f mV</b> (rests: rms up to %.1f mV).</li>', max(abs(keyErr(:))), max(T.rms_twin_mV(rst))) ...
            '<li>The <b>first charge</b> is the worst phase: the slow RC pair (&tau;3, hours) remembers the discharge before every ' ...
            'later charge, but the first charge has no discharge before it. A linear RC pair cannot forget faster when charging ' ...
            'starts; a real cell does.</li>' ...
            '<li>The slow recovery after a discharge to cut-off is one exponential in the twin; in the cell it also speeds up ' ...
            'as the cell warms from the test temperature back to 25 &deg;C.</li>' ...
            '<li>The resistances have no temperature axis: each rate''s column already contains the heating that rate causes ' ...
            'in this test. To predict other ambient temperatures, combine files from several test temperatures.</li></ul>' ...
            '</body></html>'];
    end

    function s = tableHtml()
        s = '<table><tr><th>#</th><th>Phase</th><th>h</th><th>V start</th><th>start</th><th>end</th><th>min</th><th>max</th><th>rms</th><th>Table-Based rms</th><th>T max meas / twin (&deg;C)</th></tr>';
        for r = 1:height(T)
            s = [s sprintf('<tr><td>%d</td><td>%s</td><td>%.1f</td><td>%.3f</td><td>%+.1f</td><td>%+.1f</td><td>%+.1f</td><td>%+.1f</td><td>%.1f</td><td>%.0f</td><td>%.1f / %.1f</td></tr>', ...
                T.n(r), esc(T.Phase(r)), T.Hours(r), T.Vstart(r), T.err_start_mV(r), T.err_end_mV(r), T.err_min_mV(r), ...
                T.err_max_mV(r), T.rms_twin_mV(r), T.rms_TableBased_mV(r), T.Tmax_meas_C(r), T.Tmax_twin_C(r))]; %#ok<AGROW>
        end
        s = [s '</table>'];
    end

    function s = snip(rel, pattern, n)
        % the code itself, read from the file now, with file:line
        s = '';
        try
            L = readlines(fullfile(here, rel));
            k = find(contains(L, pattern), 1);
            if isempty(k), return; end
            k2 = min(numel(L), k + n - 1);
            s = sprintf('<div class="f">%s : line %d</div><pre>%s</pre>', rel, k, esc(strjoin(L(k:k2), newline)));
        catch
        end
    end
end

function s = esc(s)
s = char(s);
s = strrep(s, '&', '&amp;'); s = strrep(s, '<', '&lt;'); s = strrep(s, '>', '&gt;');
end
